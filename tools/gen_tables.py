    for i in range(1024):
        e.append(math.floor(y + 0.5))
        y *= inc
    L += arr("FM6_EXP2", "uint32_t", e + [1 << 31], 8)
    # phase increment of a log frequency (freqlut.cc): Q24 phase, 2^20 Hz at the top of the table
