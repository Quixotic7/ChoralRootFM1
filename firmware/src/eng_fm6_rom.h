#define OPX(r1, r2, r3, r4, l1, l2, l3, l4, bp, ld, rd, lc, rc, rs, am, kv, ol, cr, fi, dt) \
    {r1, r2, r3, r4, l1, l2, l3, l4, bp, ld, rd, lc, rc, rs, am, kv, ol, 1, cr, fi, (dt) + 7}
