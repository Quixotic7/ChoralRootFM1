# the ratio steps: C and B 0.25 0.5 0.75 then 1..16 (19); A 0.25..16 in 0.25 (64); the B pair: B1 a C/B step, B2 =
# B1 x BR, BR one of six; the pair's index = BR index x 19 + B1 index (B1 cycles through its steps, then BR steps)
RCB = [0.25, 0.5, 0.75] + [float(n) for n in range(1, 17)]
RA = [0.25 * (i + 1) for i in range(64)]
BR = [0.5, 1.0, 1.5, 2.0, 3.0, 4.0]
NRB = len(RCB) * len(BR)
RB_DEF = 1 * len(RCB) + 3               # 1.00 / 1.00
LFO_K = 9739                            # SPEED x MULT x LFO_K a control tick: f = SPEED x MULT / 320 Hz
NHARM = 7


def q16(r):
    return int(round(r * 65536))


def harm_tables():
    """15 tables of 1025 points (the last = the first): 0 sine, 1..7 the odd series up to harmonic 2k + 1 (toward a
    square), 8..14 all harmonics up to 2k + 1 (toward a saw); amplitudes 1 / n, each scaled to a peak of 32767"""
    out = []
    for t in range(2 * NHARM + 1):
        k = 0 if t == 0 else (t if t <= NHARM else t - NHARM)
        odd = t <= NHARM
        hs = [n for n in range(1, 2 * k + 2) if (n % 2 == 1 or not odd)]
        raw = [sum(math.sin(2 * math.pi * n * i / 1024) / n for n in hs) for i in range(1024)]
        fine = [sum(math.sin(2 * math.pi * n * i / 8192) / n for n in hs) for i in range(8192)]
        pk = max(abs(x) for x in fine)
        tab = [int(round(32767 * x / pk)) for x in raw]
        tab = [max(-32767, min(32767, x)) for x in tab]
        out.append(tab + [tab[0]])
    return out


HARM = harm_tables()


def cutoff_hz(v):
    return 30.0 * ((16000 / 30) ** (v / 127))


BW_K = [min(65535, int(round(65536 * (1 - math.exp(-2 * math.pi * cutoff_hz(v) / FS))))) for v in range(128)]


def rtxt(r):
    return "%.2f" % r


def write_header():
    L = ["/* generated by tests/quad_ref.py: do not edit (python3 tests/quad_ref.py) */",
         "/* QUAD (eng_quad.c, docs/QUAD.md): the harmonic tables, the ratio tables, the value names */",
         "#pragma once",
         "#include <stdint.h>",
         "#define QUAD_NRCB %du                /* RATIO C (and B1): 0.25 0.5 0.75 1 2 .. 16 */" % len(RCB),
         "#define QUAD_NRA %du                 /* RATIO A: 0.25 .. 16 in 0.25 */" % len(RA),
         "#define QUAD_NBR %du                  /* the B pair's B2 / B1 */" % len(BR),
         "#define QUAD_NRB %du                /* RATIO B: BR index x QUAD_NRCB + B1 index */" % NRB,
         "#define QUAD_RB_DEF %d               /* 1.00 / 1.00 */" % RB_DEF,
         "#define QUAD_LFO_K %d              /* LFO: SPEED x MULT x QUAD_LFO_K a control tick (f = SPEED x MULT / 320 Hz) */" % LFO_K]

    def arr(name, ctype, vals, per=12):
        L.append("static const %s %s[%d] = {" % (ctype, name, len(vals)))
        for i in range(0, len(vals), per):
            L.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
        L.append("};")

    def names(name, vals):
        L.append("static const char *const %s[%d] = {" % (name, len(vals) + 1))
        for i in range(0, len(vals), 8):
            L.append("    " + ", ".join('"%s"' % v for v in vals[i:i + 8]) + ",")
        L.append("    0,")
        L.append("};")

    arr("QUAD_RCB_Q16", "int32_t", [q16(r) for r in RCB], 10)
    arr("QUAD_RA_Q16", "int32_t", [q16(r) for r in RA], 10)
    arr("QUAD_BR_Q16", "int32_t", [q16(r) for r in BR], 10)
    L.append("/* the value names (F_INT columns with a 0-terminated name list: value v - min names it) */")
    names("N_QUAD_RCB", [rtxt(r) for r in RCB])
    names("N_QUAD_RA", [rtxt(r) for r in RA])
    names("N_QUAD_RB", ["%s/%s" % (rtxt(RCB[i % len(RCB)]), rtxt(RCB[i % len(RCB)] * BR[i // len(RCB)])) for i in range(NRB)])
    names("N_QUAD_OFS", [("+" if o >= 0 else "-") + "%d.%02d" % (abs(o) // 100, abs(o) % 100) for o in range(-100, 101)])
    L.append("/* the base-width filter: a one-pole's coefficient (Q16) at 30 Hz x (16000 / 30)^(v / 127) (CUTOFF_HZ's scale) */")
    arr("QUAD_BW_K", "uint16_t", BW_K)
    L.append("/* HARM: 0 sine, 1..7 odd harmonics up to 3 5 .. 15, 8..14 all harmonics up to 3 5 .. 15 (1 / n, peak 32767);")
    L.append(" * 1024 points and the first again (no wrap in the interpolation). Flash (XIP): 30.8 KB */")
    L.append("static const int16_t QUAD_HARM[%d][1025] = {" % len(HARM))
    for t in HARM:
        L.append("    {")
        for i in range(0, 1025, 16):
            L.append("        " + ", ".join(str(v) for v in t[i:i + 16]) + ",")
        L.append("    },")
    L.append("};")
    with open(OUT_H, "w") as f:
        f.write("\n".join(L) + "\n")


