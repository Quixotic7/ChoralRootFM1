def felucca_table(name):
    src = open(TABLES).read()
    m = re.search(r"\b%s\[\d*\]\s*=\s*\{(.*?)\};" % name, src, re.S)
    if not m:
        sys.exit("quad_ref: %s not in %s (build the generated tables first)" % (name, TABLES))
    return [int(x) for x in re.findall(r"-?\d+", m.group(1))]


